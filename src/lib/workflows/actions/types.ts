async function lstatIfPresent(target: string): Promise<Awaited<ReturnType<typeof fs.lstat>> | undefined> {
  try {
    return await fs.lstat(target)
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return undefined
    throw error
  }
}

async function assertGeneratedFileWritable(file: string): Promise<void> {
  const stat = await lstatIfPresent(file)
  if (!stat) return
  if (stat.isSymbolicLink()) throw new Error(`Generated action type file "${file}" cannot be a symbolic link.`)
  if (!stat.isFile()) throw new Error(`Generated action type path "${file}" is not a regular file.`)
  const contents = await fs.readFile(file, 'utf8')
  if (!contents.includes(GENERATED_MARKER)) {
    throw new Error(`Action type file "${file}" is developer-owned and will not be overwritten.`)
  }
}

async function migrateLegacyActionTypeImports(directory: string, manifest: WorkflowActionsManifest): Promise<void> {
  await Promise.all(
    manifest.actions.flatMap(action =>
      action.versions.map(async version => {
        const file = path.join(
          directory,
          WORKFLOW_ACTION_CODE_RELATIVE_DIRECTORY,
          workflowActionCodeFilename(action.key, version.version, 'typescript')
        )
        const stat = await lstatIfPresent(file)
        if (!stat) return
        if (stat.isSymbolicLink()) throw new Error(`Workflow action code file "${file}" cannot be a symbolic link.`)
        if (!stat.isFile()) throw new Error(`Workflow action code path "${file}" is not a regular file.`)
        const source = await fs.readFile(file, 'utf8')
        const legacySpecifier = `../../../../../ghl-action-${action.key}`
        const nextSpecifier = `../../../../../.ghl/types/actions/${action.key}`
        const migrated = source
          .replaceAll(`from '${legacySpecifier}'`, `from '${nextSpecifier}'`)
          .replaceAll(`from "${legacySpecifier}"`, `from "${nextSpecifier}"`)
        if (migrated !== source) await writeTextFileAtomic(file, migrated, Number(stat.mode) & 0o777)
      })
    )
  )
}

function workflowActionTypeWorkspacePaths(
  inputDirectory: string,
  manifest: WorkflowActionsManifest
): WorkflowActionTypesWorkspaceResult {
  const directory = path.resolve(inputDirectory)
  const typesDirectory = path.join(directory, WORKFLOW_ACTION_TYPES_RELATIVE_DIRECTORY)
  return {
    sandboxDeclarationFile: path.join(typesDirectory, WORKFLOW_ACTION_SANDBOX_TYPES_FILENAME),
    typescriptConfigFile: path.join(
      directory,
      WORKFLOW_ACTION_TYPESCRIPT_CONFIG_RELATIVE_DIRECTORY,
      WORKFLOW_ACTION_TYPESCRIPT_CONFIG_FILENAME
    ),
    actionDeclarationFiles: manifest.actions.map(action =>
      path.join(typesDirectory, workflowActionTypeFilename(action.key))
    )
  }
}

async function assertGeneratedDirectoryPathSafe(directory: string): Promise<void> {
  let current = directory
  for (const part of WORKFLOW_ACTION_TYPES_RELATIVE_DIRECTORY.split(path.sep)) {
    current = path.join(current, part)
    const stat = await lstatIfPresent(current)
    if (!stat) continue
    if (stat.isSymbolicLink())
      throw new Error(`Generated action type directory "${current}" cannot be a symbolic link.`)
    if (!stat.isDirectory()) throw new Error(`Generated action type path "${current}" is not a directory.`)
  }
}

export async function assertWorkflowActionTypesWorkspaceWritable(
  inputDirectory: string,
  manifest: WorkflowActionsManifest
): Promise<void> {
  const directory = path.resolve(inputDirectory)
  const files = workflowActionTypeWorkspacePaths(inputDirectory, manifest)
  await Promise.all([
    assertGeneratedDirectoryPathSafe(directory),
    ...[files.sandboxDeclarationFile, files.typescriptConfigFile, ...files.actionDeclarationFiles].map(
      assertGeneratedFileWritable
    )
  ])
}

export async function writeWorkflowActionTypesWorkspace(
  inputDirectory: string,
  manifest: WorkflowActionsManifest,
  options: WorkflowActionTypeOptions = {}
): Promise<WorkflowActionTypesWorkspaceResult> {
  const directory = path.resolve(inputDirectory)
  const generatedAt = options.generatedAt ?? new Date()
  const { sandboxDeclarationFile, typescriptConfigFile, actionDeclarationFiles } = workflowActionTypeWorkspacePaths(
    directory,
    manifest
  )
  await assertWorkflowActionTypesWorkspaceWritable(directory, manifest)
  const typesDirectory = path.dirname(sandboxDeclarationFile)
  await Promise.all([
    fs.mkdir(typesDirectory, { recursive: true, mode: 0o755 }),
    fs.mkdir(path.dirname(typescriptConfigFile), { recursive: true, mode: 0o755 })
  ])
  await Promise.all([
    writeTextFileAtomic(sandboxDeclarationFile, generateWorkflowActionSandboxDeclarations(generatedAt), 0o644),
    writeTextFileAtomic(typescriptConfigFile, actionTypeScriptConfig(), 0o644),
    ...manifest.actions.map((action, index) =>
      writeTextFileAtomic(actionDeclarationFiles[index], generateWorkflowActionDeclaration(action, generatedAt), 0o644)
    )
  ])
  await migrateLegacyActionTypeImports(directory, manifest)

  const desired = new Set(actionDeclarationFiles.map(file => path.basename(file)))
  const entries = await fs.readdir(typesDirectory, { withFileTypes: true })
  await Promise.all(
    entries
      .filter(
        entry =>
          entry.isFile() &&
          entry.name !== WORKFLOW_ACTION_SANDBOX_TYPES_FILENAME &&
          ACTION_TYPES_PATTERN.test(entry.name) &&
          !desired.has(entry.name)
      )
      .map(entry => removeGeneratedFile(path.join(typesDirectory, entry.name)))
  )
  const rootEntries = await fs.readdir(directory, { withFileTypes: true })
  await Promise.all(
    rootEntries
      .filter(
        entry =>
          entry.isFile() &&
          (entry.name === LEGACY_SANDBOX_TYPES_FILENAME || LEGACY_ACTION_TYPES_PATTERN.test(entry.name))
      )
      .map(entry => removeGeneratedFile(path.join(directory, entry.name)))
  )
  return { sandboxDeclarationFile, actionDeclarationFiles, typescriptConfigFile }
}

async function removeGeneratedFile(file: string): Promise<void> {
  const stat = await lstatIfPresent(file)
  if (!stat) return
  if (stat.isSymbolicLink() || !stat.isFile()) return
  const contents = await fs.readFile(file, 'utf8')
  if (contents.includes(GENERATED_MARKER)) await fs.unlink(file)
}

export async function removeWorkflowActionTypesWorkspace(inputDirectory: string): Promise<void> {
  const directory = path.resolve(inputDirectory)
  const typesDirectory = path.join(directory, WORKFLOW_ACTION_TYPES_RELATIVE_DIRECTORY)
  const typesDirectoryStat = await lstatIfPresent(typesDirectory)
  const entries = typesDirectoryStat?.isDirectory() ? await fs.readdir(typesDirectory, { withFileTypes: true }) : []
  const declarationFiles = entries
    .filter(
      entry =>
        entry.isFile() &&
        (entry.name === WORKFLOW_ACTION_SANDBOX_TYPES_FILENAME || ACTION_TYPES_PATTERN.test(entry.name))
    )
    .map(entry => path.join(typesDirectory, entry.name))
  const rootEntries = await fs.readdir(directory, { withFileTypes: true })
  const legacyDeclarationFiles = rootEntries
    .filter(
      entry =>
        entry.isFile() && (entry.name === LEGACY_SANDBOX_TYPES_FILENAME || LEGACY_ACTION_TYPES_PATTERN.test(entry.name))
    )
    .map(entry => path.join(directory, entry.name))
  const configFile = path.join(
    directory,
    WORKFLOW_ACTION_TYPESCRIPT_CONFIG_RELATIVE_DIRECTORY,
    WORKFLOW_ACTION_TYPESCRIPT_CONFIG_FILENAME
  )
  await Promise.all([...declarationFiles, ...legacyDeclarationFiles, configFile].map(removeGeneratedFile))
  if (typesDirectoryStat?.isDirectory()) await removeEmptyDirectoryTree(typesDirectory, directory)
}
