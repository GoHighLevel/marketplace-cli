function generatedHeader(generatedAt: Date, source?: string): string {
  if (Number.isNaN(generatedAt.getTime())) throw new Error('Generated-at timestamp must be a valid date.')
  return [
    '/*',
    ` * ${GENERATED_MARKER} on ${generatedAt.toISOString()}.`,
    ...(source ? [` * Source: ${source}.`] : []),
    ' * Run `ghl app types` to regenerate. Do not edit manually.',
    ' */'
  ].join('\n')
}

function pascalCase(value: string): string {
  const result = value
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map(part => part[0].toUpperCase() + part.slice(1))
    .join('')
  return result || 'Action'
}

