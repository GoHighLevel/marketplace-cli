function stringLiteral(value: string): string {
  return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'").replaceAll('\n', '\\n').replaceAll('\r', '\\r')}'`
}

function optionType(input: WorkflowActionInput): string {
  const values = input.options?.map(option => option.value).filter((value, index, all) => all.indexOf(value) === index)
  return values && values.length > 0 ? values.map(stringLiteral).join(' | ') : 'string'
}

function inputType(input: WorkflowActionInput): string {
  switch (input.fieldType) {
    case 'numerical':
      return 'number | string'
    case 'checkbox':
    case 'toggle':
      return 'boolean | string'
    case 'select':
    case 'radio':
    case 'select_with_pagination':
      return optionType(input)
    case 'multiselect':
    case 'multiselect_with_pagination':
    case 'tags':
      return `ReadonlyArray<${optionType(input)}>`
    case 'key-value':
      return 'Readonly<Record<string, string>>'
    case 'fieldSet':
      return 'ReadonlyArray<Readonly<Record<string, unknown>>>'
    case 'attachment':
      return 'ReadonlyArray<unknown> | string'
    case 'DYNAMIC':
    case 'custom-html':
      return 'unknown'
    default:
      return 'string'
  }
}

function propertyName(value: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(value) ? value : JSON.stringify(value)
}

function cleanDescription(value: string): string {
  return value.replaceAll('*/', '* /').replace(/\s+/g, ' ').trim()
}

function inputDescription(input: WorkflowActionInput): string[] {
  const summary = [input.required === true ? 'Required.' : 'Optional.', input.title]
  if (input.helpText?.trim()) summary.push(cleanDescription(input.helpText))
  if (input.validations?.length) {
    summary.push(`Validation: ${input.validations.map(validation => validation.rule).join(', ')}.`)
  }
  return ['  /**', `   * ${cleanDescription(summary.join(' '))}`, '   */']
}

function renderDataType(action: WorkflowActionDefinition, version: WorkflowActionVersion): string {
  const name = `${workflowActionVersionTypePrefix(action.key, version.version)}Data`
  const inputs = version.inputs ?? []
  const dynamic = inputs.some(input => input.field === 'DYNAMIC' || input.fieldType === 'DYNAMIC')
  const properties = inputs.flatMap(input => {
    if (input.field === 'DYNAMIC' || input.fieldType === 'DYNAMIC') return []
    return [
      ...inputDescription(input),
      `  readonly ${propertyName(input.field)}${input.required === true ? '' : '?'}: ${inputType(input)};`
    ]
  })
  const object = properties.length > 0 ? ['{', ...properties, '}'].join('\n') : 'Readonly<Record<string, never>>'
  const rendered = dynamic
    ? properties.length > 0
      ? `Readonly<Record<string, unknown>> & ${object}`
      : 'Readonly<Record<string, unknown>>'
    : object
  return `export type ${name} = ${rendered};`
}

function renderJsonType(value: unknown, level: number): string {
  if (value === null) return 'null'
  if (typeof value === 'string') return 'string'
  if (typeof value === 'number') return 'number'
  if (typeof value === 'boolean') return 'boolean'
  if (Array.isArray(value)) {
    if (value.length === 0) return 'ReadonlyArray<unknown>'
    const itemTypes = [...new Set(value.map(item => renderJsonType(item, level)))]
    return `ReadonlyArray<${itemTypes.join(' | ')}>`
  }
  if (typeof value !== 'object' || value === undefined) return 'unknown'
  const entries = Object.entries(value)
  if (entries.length === 0) return 'Readonly<Record<string, unknown>>'
  const indentation = '  '.repeat(level)
  return [
    '{',
    ...entries.map(
      ([key, child]) => `${'  '.repeat(level + 1)}readonly ${propertyName(key)}: ${renderJsonType(child, level + 1)};`
    ),
    `${indentation}}`
  ].join('\n')
}

function renderOutputType(action: WorkflowActionDefinition, version: WorkflowActionVersion): string {
  const name = `${workflowActionVersionTypePrefix(action.key, version.version)}Output`
  const output = version.customVarsJson
  if (output && !Array.isArray(output) && Object.keys(output).length > 0) {
    return `export interface ${name} ${renderJsonType(output, 0)}`
  }
  return `export type ${name} = GhlActionOutput;`
}

export function generateWorkflowActionDeclaration(action: WorkflowActionDefinition, generatedAt = new Date()): string {
  const declarations = action.versions.flatMap(version => {
    const prefix = workflowActionVersionTypePrefix(action.key, version.version)
    return [
      renderDataType(action, version),
      renderOutputType(action, version),
      `export type ${prefix}Handler = GhlActionHandler<${prefix}Data, ${prefix}Output>;`
    ]
  })
  return `${generatedHeader(generatedAt, `${action.key}.json`)}\n\nimport type { GhlActionHandler, GhlActionOutput } from './sandbox'\n\n${declarations.join('\n\n')}\n`
}

